const isSeasoningName = (name) => {
  const n = (name ?? "").trim();
  if (!n) return false;
  if (n === "牛油果" || n === "油桃") return false;
  return SEASONINGS.has(n);
};

// ---------- 名称清理（去掉结尾的数量/单位/括号说明）----------
const cleanIngredientName = (rawName) => {
  let n = (rawName ?? "").trim();
  if (!n) return n;
  // 去掉结尾的括号说明（可多层）
  let prev;
  do {
    prev = n;
    n = n.replace(/[（(][^（）()]*[）)]\s*$/u, "").trim();
  } while (n !== prev);
  // 去掉结尾句号
  n = n.replace(/[。．.]+\s*$/u, "").trim();
  // 去掉结尾的"等"
  n = n.replace(/等\s*$/u, "").trim();
  // 去掉结尾的数量 + 单位（含范围，如 3-4 朵）
  n = n
    .replace(
      /[\s]*([0-9０-９]+[.,．]?[0-9０-９]*(?:[-－–—~～][0-9０-９]+[.,．]?[0-9０-９]*)?|半|少许|适量|若干|数个|数块|一小把|一大把|几滴)\s*(克|g|公斤|毫升|ml|升|l|大勺|小勺|大匙|小匙|茶匙|勺|匙|朵|根|段|小段|块|片|个|把|小把|大把|人份|份|盒|碗|杯|条|颗|粒|滴)?\s*$/u,
      "",
    )
    .trim();
  return n;
};

// ---------- 括号感知的食材名切分 ----------
const splitNames = (text) => {
  const parts = [];
  let buf = "";
  let depth = 0;
  for (const ch of text) {
    if (ch === "（" || ch === "(") depth += 1;
    if (ch === "）" || ch === ")") depth = Math.max(0, depth - 1);
    if ((ch === "、" || ch === "，" || ch === "," || ch === ";" || ch === "；") && depth === 0) {
      parts.push(buf);
      buf = "";
    } else {
      buf += ch;
    }
  }
  parts.push(buf);
  return parts.map((s) => s.trim()).filter(Boolean);
};

const toItem = (name, category) => ({ id: createId(), name, category, amount: "", unit: "" });

// ---------- 笔记切分 ----------
const NOTE_MARK = /^【(\d+)】/;

const splitNotes = (text) => {
  const lines = text.split(/\r?\n/);
  const notes = [];
  let current = null;

  for (const line of lines) {
    const marker = line.match(NOTE_MARK);
    if (marker) {
      if (current) notes.push(current);
      current = { noteNum: Number(marker[1]), category: "", lines: [] };
      continue;
    }
    if (!current) continue;
    const trimmed = line.trim();
    if (current.category === "" && trimmed.startsWith("#")) {
      const seg = trimmed.split("/").filter(Boolean).pop() ?? "";
      current.category = seg.trim();
      continue;
    }
    if (current.lines.length === 0 && (trimmed === "" || /^-{3,}$/.test(trimmed))) {
      continue;
    }
    current.lines.push(trimmed);
  }
  if (current) notes.push(current);
  return notes;
};

// ---------- 通用解析：单条笔记内按「食材：」切分 ----------
const FIELD_LINE = /^(食材|调味|调味料|调料|配菜|酱料|酱汁|沙拉汁|沙拉酱|油醋汁|麻酱|汤底|蘸料|中式烧烤|可选调料|大阪烧酱|花生酱沙拉汁|无油腰果蛋黄酱)\s*[:：]/;

const METHOD_LINE = /^做法/;

const NON_TITLE_LINE =
  /^(#|【|Ref|ref|搭配|食材|调味|调料|做法|配菜|酱料|酱汁|沙拉汁|沙拉酱|油醋汁|麻酱|汤底|蘸料|中式烧烤|可选调料|大阪烧酱|花生酱沙拉汁|无油腰果蛋黄酱|https?:\/\/|b23\.|mp\.weixin|www\.|xiachufang|bilibili|eleanorrecipes|小红书)/;

const isTitleLine = (line) => {
  const t = line.trim();
  return Boolean(t) && !t.startsWith("#") && !t.startsWith("【") && !/^-{3,}$/.test(t) && !t.startsWith("- ") && !NON_TITLE_LINE.test(t);
};

const fieldText = (line) => line.replace(/^[^\s：:]*\s*[:：]\s*/, "").trim();
const methodText = (line) => line.replace(/^做法[^\s：:]*\s*[:：]\s*/, "").trim();

const stripMethodNoise = (lines) =>
  lines.filter((line) => {
    const t = line.trim();
    if (!t) return false;
    if (t.startsWith("- ")) return false;
    if (/^(Ref|ref)\s*[:：]/.test(t)) return false;
    if (/^https?:\/\//.test(t)) return false;
    if (/^小红书/.test(t)) return false;
    if (/^【/.test(t)) return false;
    if (/^搭配\s*[:：]/.test(t)) return false;
    if (/^-{3,}$/.test(t)) return false;
    return true;
  });

const parseNoteRecipes = (note) => {
  const lines = note.lines;
  const anchors = lines.reduce((acc, line, index) => (/^食材\s*[:：]/.test(line) ? [...acc, index] : acc), []);
  const recipes = [];

  for (let i = 0; i < anchors.length; i += 1) {
    const start = anchors[i];
    const nextAnchor = anchors[i + 1] ?? lines.length;

    // 标题：向上找最近的标题行
    let title = "";
    for (let index = start - 1; index >= 0; index -= 1) {
      if (isTitleLine(lines[index])) {
        title = lines[index];
        break;
      }
    }

    // 下一块标题行（用于截断本块做法/原文，避免串入下一条标题）
    let nextTitleIndex = -1;
    if (i + 1 < anchors.length) {
      for (let index = anchors[i + 1] - 1; index >= 0; index -= 1) {
        if (isTitleLine(lines[index])) {
          nextTitleIndex = index;
          break;
        }
      }
    }
    const bodyEnd = nextTitleIndex >= 0 ? nextTitleIndex : lines.length;

    // 做法行
    const methodLineIndex = lines
      .slice(start + 1, bodyEnd)
      .findIndex((line) => METHOD_LINE.test(line));
    const methodLine = methodLineIndex >= 0 ? start + 1 + methodLineIndex : -1;
    const methodEnd = methodLine >= 0 ? bodyEnd : start;

    // 食材与调味料
    const itemNames = [];
    for (let index = start; index < (methodLine >= 0 ? methodLine : bodyEnd); index += 1) {
      const line = lines[index];
      if (FIELD_LINE.test(line)) {
        itemNames.push(...splitNames(fieldText(line)));
      }
    }

    const method =
      methodLine >= 0
        ? stripMethodNoise([methodText(lines[methodLine]), ...lines.slice(methodLine + 1, methodEnd)]).join("\n")
        : "";

    recipes.push({
      id: createId(),
      title,
      type: "full",
      category: note.category,
      ingredients: itemNames
        .map((name) => cleanIngredientName(name))
        .filter(Boolean)
        .map((name) => toItem(name, isSeasoningName(name) ? "调味料" : "食材"))
        .filter((item, index, arr) => arr.findIndex((x) => x.name === item.name) === index),
      method,
      rawText: lines.slice(start, bodyEnd).join("\n"),
      createdAt: now(),
      updatedAt: now(),
    });
  }

  return recipes;
};


const buildOverrideRecipes = (note, specs) =>
  specs.map((spec) => ({
    id: createId(),
    title: spec.t,
    type: "full",
    category: note.category,
    ingredients: (spec.ing ?? [])
      .map((name) => toItem(name, isSeasoningName(name) ? "调味料" : "食材"))
      .filter((item, index, arr) => arr.findIndex((x) => x.name === item.name) === index),
    method: spec.m ?? "",
    rawText: "",
    createdAt: now(),
    updatedAt: now(),
  }));

// ---------- flomo 文本解析 ----------
const parseFlomo = (text) => {
  const notes = splitNotes(text);
  const recipes = [];
  for (const note of notes) {
    const override = NOTE_OVERRIDES[note.noteNum];
    if (override) {
      recipes.push(...buildOverrideRecipes(note, override));
    } else {
      recipes.push(...parseNoteRecipes(note));
    }
  }
  return recipes.filter((recipe) => recipe.title);
};

// ---------- 从 App 导出 JSON 提取并归一化 ----------
const fromAppExport = (json) => {
  const data = JSON.parse(json);
  const list = Array.isArray(data.recipes) ? data.recipes : [];
  const normalizeCategory = (value) => (value === "调味料" || value === "调料" ? "调味料" : "食材");
  return list
    .map((recipe) => ({
      id: recipe.id ?? createId(),
      title: (recipe.title ?? recipe.name ?? "").trim(),
      type: recipe.type === "simple" ? "simple" : "full",
      category: recipe.category ?? "",
      ingredients: [...(recipe.ingredients ?? []), ...(recipe.seasonings ?? [])]
        .filter((item) => item && typeof item.name === "string" && item.name.trim())
        .map((item) => ({
          id: item.id ?? createId(),
          name: item.name.trim(),
          category: normalizeCategory(item.category),
          amount: typeof item.amount === "string" ? item.amount : "",
          unit: typeof item.unit === "string" ? item.unit : "",
        })),
      method: (recipe.method ?? recipe.steps ?? "").trim(),
      rawText: (recipe.rawText ?? recipe.notes ?? "").trim(),
      createdAt: recipe.createdAt ?? now(),
      updatedAt: recipe.updatedAt ?? now(),
    }))
    .filter((recipe) => recipe.title);
};

let recipes = [];
if (inputMode === "app") {
  recipes = fromAppExport(readInput());
} else {
  recipes = parseFlomo(readInput());
}

if (!recipes.length) {
  console.error("未解析到任何食谱：请确认文本包含「食材：」行，或检查文件路径。");
  process.exit(1);
}

writeFileSync("recipes.json", JSON.stringify({ recipes }, null, 2), "utf8");
console.log(`✅ 已生成 recipes.json，共 ${recipes.length} 个食谱（食材与调味料已分开）。`);
